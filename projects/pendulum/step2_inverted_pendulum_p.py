# -*- coding: utf-8 -*-
"""
台阶 2：倒立摆 + 比例控制(P 控制)
===================================
目标：在摆杆的转轴处加一个"电机力矩"，用最简单的 P 控制把摆杆立到竖直向上。

【和台阶 1 的关键区别】
    台阶 1 的 θ=0 是"竖直向下"（稳定，摆自然往下掉）。
    台阶 2 的 θ=0 是"竖直向上"（不稳定，摆自然往下倒）——所以必须用力矩扶住它。

【物理：摆杆为什么会倒，力矩怎么扶】
    重力想让摆杆倒下（不稳定）：   θ''_重力 = (g / L) · sin(θ)
    电机力矩想让摆杆回正：         θ''_力矩 = τ / I
    总角加速度：                   θ'' = θ''_重力 + θ''_力矩

    其中 I 是摆杆绕转轴的转动惯量，这里用质点近似 I = m · L²。

【P 控制是什么】
    τ = -Kp · θ
    意思：摆杆往右歪(θ>0)，就给一个把它往左掰的力矩；歪得越厉害，掰得越用力。

【你需要完成 4 个填空】
    TODO 1：用 P 控制算出力矩 τ
    TODO 2：算出总角加速度 θ''
    TODO 3：欧拉积分更新角速度
    TODO 4：欧拉积分更新角度

【填完后的预期】
    摆杆不会倒，会立在竖直向上附近，但会"来回振荡"（因为只有 P 没有 D）。
    这正是台阶 3 要解决的问题。

【关于时间步长 dt】
    台阶 1 用的 dt=0.01，这里改成了 dt=0.001。
    因为倒立摆变化快、系统更"硬"，步长太大误差会很大甚至发散。
"""

import numpy as np
import matplotlib.pyplot as plt

# ---------- 1. 物理参数 ----------
g = 9.81      # 重力加速度 (m/s²)
L = 1.0       # 摆长 (m)
m = 0.5       # 摆杆质量 (kg)
I = m * L**2  # 转动惯量（质点近似：质量 × 摆长²）

# ---------- 2. 控制参数 ----------
Kp = 20.0     # P 控制增益（可以调！调太小摆杆会倒，太大振荡更剧烈）

# ---------- 3. 模拟参数 ----------
dt = 0.001    # 时间步长 (s)
t_end = 5.0   # 模拟总时长 (s)

# ---------- 4. 初始状态 ----------
theta = np.radians(15)   # 初始角度 15°（从竖直向上偏开一点）
theta_dot = 0.0          # 初始角速度 0

time_list = []
theta_list = []

t = 0.0
while t < t_end:
    # 【TODO 1】用 P 控制算出力矩 τ
    # 公式：tau = -Kp * theta
    tau = -Kp * theta

    # 【TODO 2】算出总角加速度
    # 重力项(想让摆倒) + 力矩项(想扶正)
    # 公式：theta_ddot = (g / L) * sin(theta) + tau / I
    theta_ddot = (g / L) * np.sin(theta) + tau / I

    # 【TODO 3】欧拉积分：更新角速度
    # 新角速度 = 旧角速度 + 角加速度 * dt
    theta_dot = theta_ddot *dt + theta_dot

    # 【TODO 4】欧拉积分：更新角度
    # 新角度 = 旧角度 + 角速度 * dt
    theta = theta + theta_dot * dt

    # 记录数据（不用改）
    time_list.append(t)
    theta_list.append(theta)

    # 时间前进（不用改）
    t += dt

# ---------- 5. 画图 ----------
plt.plot(time_list, theta_list)
plt.xlabel('时间 (s)')
plt.ylabel('角度 (弧度)')
plt.title('倒立摆 P 控制：角度随时间变化')
plt.grid(True)
plt.show()
