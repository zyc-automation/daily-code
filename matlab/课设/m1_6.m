% ============================================================
% 实验报告1《机器人建模与仿真实验A》第六题
% MATLAB 图形绘制 plot / subplot / figure
% 绘制包含一行 1×3 子图的图
% ============================================================
clear; clc; close all;

% ---------- 第一张子图：y = cos(x) + 3*sin(x)，x ∈ [0, 4π] ----------
subplot(1,3,1);
x1 = 0 : 0.01 : 4*pi;                 % 区间 [0, 4π]
y1 = cos(x1) + 3*sin(x1);
plot(x1, y1, '-', 'LineWidth', 3);    % 线型实线，线宽 3
xlabel('x');                          % 标识 x 轴
ylabel('y');                          % 标识 y 轴
title('y = cos(x) + 3sin(x)');
grid on;

% ---------- 第二张子图：z1=cos(2x)（虚线）、z2=sin(x/2)（点划线），x ∈ [0, 4π] ----------
subplot(1,3,2);
x2 = 0 : 0.01 : 4*pi;                 % 区间 [0, 4π]
z1 = cos(2*x2);
z2 = sin(x2/2);
plot(x2, z1, '--', 'LineWidth', 5);   % z1 用虚线，线宽 5
hold on;
plot(x2, z2, '-.', 'LineWidth', 5);   % z2 用点划线，线宽 5
hold off;
xlabel('x');
ylabel('y');
legend('z1 = cos(2x)', 'z2 = sin(x/2)');
grid on;

% ---------- 第三张子图：分段函数 ----------
subplot(1,3,3);
% 分段函数定义：
%   y = 3*sin(2x + pi/3)^2 ,   -9 <= x < 0
%   y = 4*sqrt(x) - 1       ,    0 <= x < 7
%   y = x^7 + 2*x           ,    7 <= x < 18
x31 = -9 : 0.01 : -0.01;
y31 = 3 * sin(2*x31 + pi/3).^2;
x32 = 0 : 0.01 : 6.99;
y32 = 4 * sqrt(x32) - 1;
x33 = 7 : 0.01 : 17.99;
y33 = x33.^7 + 2*x33;
% 注意：若文档第三段实为 x*e^7 + 2x（x 乘以 e 的 7 次方），
%       请将上一行替换为： y33 = x33 .* exp(7) + 2*x33;
plot(x31, y31, 'b', x32, y32, 'r', x33, y33, 'g');
xlabel('x');
ylabel('y');
title('分段函数');
grid on;
